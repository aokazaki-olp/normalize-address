import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { rewriteForParser } from '../../../src/domain/split/rewrites.ts';

describe('rewriteForParser', () => {
  const cases: [string, string, string][] = [
    [
      '京都市の通り名を外す',
      '京都市下京区四条通室町西入月鉾町63月鉾町ビル8階',
      '京都市下京区月鉾町63月鉾町ビル8階',
    ],
    [
      '送り仮名のある通り名を外す',
      '京都府京都市中京区烏丸通四条上る笋町691',
      '京都府京都市中京区笋町691',
    ],
    [
      'ルの付く通り名を外す',
      '京都市中京区三条通高倉東入ル枡屋町57',
      '京都市中京区枡屋町57',
    ],
    [
      '通り名のあとが数字なら外さない',
      '京都市中京区錦小路通室町西入ル282',
      '京都市中京区錦小路通室町西入ル282',
    ],
    [
      '京都市でなければ外さない',
      '大阪府大阪市北区梅田西入町1',
      '大阪府大阪市北区梅田西入町1',
    ],
    [
      '東京都市で始まる名前は京都市とみなさない',
      '東京都市ヶ谷区上ル町1',
      '東京都市ヶ谷区上ル町1',
    ],
    [
      '番号のあとの通り名は外さない',
      '京都市中京区桝屋町58番地 西入ルビル',
      '京都市中京区桝屋町58番地 西入ルビル',
    ],
    [
      '読点の列挙の2つ目からの番地をハイフンにする',
      'あきる野市草花1439番地9、1444番地1',
      'あきる野市草花1439番地9、1444-1',
    ],
    [
      '中黒の列挙は変えない',
      '東近江市八日市浜野町503番地・505番地1',
      '東近江市八日市浜野町503番地・505番地1',
    ],
    [
      'および を 及び にし、そのあとの番地もハイフンにする',
      '大牟田市宝坂町一丁目1番地28および1番地9',
      '大牟田市宝坂町一丁目1番地28及び1-9',
    ],
  ];
  for (const [name, input, expected] of cases) {
    it(name, () => {
      assert.equal(rewriteForParser(input), expected);
    });
  }
});
